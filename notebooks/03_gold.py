# MAGIC
# MAGIC ```
# MAGIC              dim_date
# MAGIC                  |
# MAGIC dim_product -- fact_sales -- dim_customer
# MAGIC                  |
# MAGIC             dim_country
# MAGIC ```
# MAGIC - **fact_sales**, grain: one invoice line (one row of `retail_silver.sales_lines`).
# MAGIC - **Dimensions**: integer surrogate keys from Delta identity columns. They are loaded with
# MAGIC   `MERGE` as **SCD Type 1** (attributes are overwritten with the latest value, no history), so
# MAGIC   keys stay stable across reruns.
# MAGIC - **Unknown member** (`key = -1`) in every dimension: guest sales have no customer, but the fact
# MAGIC   foreign key is never NULL.
# MAGIC - **dim_date** is generated (calendar table), keyed by `yyyymmdd` (a smart key, the usual exception for dates).
# MAGIC - **dim_country** exists because 22% of lines have no customer. Revenue by country therefore
# MAGIC   uses the country on the invoice, not the customer's country.

