from pyspark.sql import functions as F

silver = spark.table(T_SILVER)
silver.createOrReplaceTempView("silver_lines")

# COMMAND ----------

# MAGIC %md ## dim_date (generated)

# COMMAND ----------

bounds = silver.agg(F.min("invoice_date").alias("lo"), F.max("invoice_date").alias("hi")).first()
dim_date = spark.sql(f"""
    SELECT
      CAST(date_format(d, 'yyyyMMdd') AS INT) AS date_key,
      d                                       AS full_date,
      year(d)                                 AS year,
      quarter(d)                              AS quarter,
      month(d)                                AS month,
      date_format(d, 'MMMM')                  AS month_name,
      date_format(d, 'yyyy-MM')               AS year_month,
      day(d)                                  AS day_of_month,
      weekday(d) + 1                          AS day_of_week,   -- 1 = Monday
      date_format(d, 'EEEE')                  AS day_name,
      weekofyear(d)                           AS week_of_year,
      weekday(d) >= 5                         AS is_weekend
    FROM (SELECT explode(sequence(
            date_trunc('YEAR', DATE'{bounds.lo}')::date,
            last_day(make_date(year(DATE'{bounds.hi}'), 12, 1)),
            INTERVAL 1 DAY)) AS d)
""")
dim_date.write.format("delta").mode("overwrite").option("overwriteSchema", True).saveAsTable(T_DIM_DATE)

# COMMAND ----------

# MAGIC %md ## Dimensions: identity surrogate keys + SCD Type 1 MERGE

# COMMAND ----------

def scd1_merge(target, ddl_columns, natural_key, source_sql, attributes, unknown_values):
    """Create the dimension if missing, upsert the unknown member, then SCD1-merge the source."""
    spark.sql(f"""
        CREATE TABLE IF NOT EXISTS {target} (
          {ddl_columns},
          _updated_at TIMESTAMP
        )
    """)
    key_col = ddl_columns.split()[0]
    cols = [key_col, natural_key, *attributes]
    spark.sql(f"""
        MERGE INTO {target} t
        USING (SELECT {UNKNOWN_KEY} AS {key_col}, {unknown_values}) s
        ON t.{key_col} = s.{key_col}
        WHEN NOT MATCHED THEN INSERT ({", ".join(cols)}, _updated_at)
          VALUES ({", ".join("s." + c for c in cols)}, current_timestamp())
    """)
    changed = " OR ".join(f"NOT (t.{a} <=> s.{a})" for a in attributes)
    sets = ", ".join(f"t.{a} = s.{a}" for a in attributes)
    ins_cols = [natural_key, *attributes]
    spark.sql(f"""
        MERGE INTO {target} t
        USING ({source_sql}) s
        ON t.{natural_key} = s.{natural_key}
        WHEN MATCHED AND ({changed}) THEN UPDATE SET {sets}, t._updated_at = current_timestamp()
        WHEN NOT MATCHED THEN INSERT ({", ".join(ins_cols)}, _updated_at)
          VALUES ({", ".join("s." + c for c in ins_cols)}, current_timestamp())
    """)


scd1_merge(
    T_DIM_PRODUCT,
    ddl_columns="""product_key BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
          stock_code STRING NOT NULL, description STRING, is_non_merchandise BOOLEAN,
          first_sold_date DATE, last_sold_date DATE""",
    natural_key="stock_code",
    source_sql="""
        SELECT stock_code,
               -- a stock code has several descriptions in the source: SCD1 keeps the latest one
               coalesce(max_by(description, CASE WHEN description IS NOT NULL THEN invoice_ts END),
                        'Unknown description') AS description,
               bool_or(is_non_merchandise) AS is_non_merchandise,
               min(invoice_date) AS first_sold_date,
               max(invoice_date) AS last_sold_date
        FROM silver_lines GROUP BY stock_code""",
    attributes=["description", "is_non_merchandise", "first_sold_date", "last_sold_date"],
    unknown_values="'UNKNOWN' AS stock_code, 'Unknown product' AS description, "
    "false AS is_non_merchandise, NULL AS first_sold_date, NULL AS last_sold_date",
)

scd1_merge(
    T_DIM_CUSTOMER,
    ddl_columns="""customer_key BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
          customer_id INT, country STRING, first_purchase_date DATE, last_purchase_date DATE""",
    natural_key="customer_id",
    source_sql="""
        SELECT customer_id,
               max_by(country, invoice_ts) AS country,  -- 13 customers bought from 2 countries: latest wins
               min(invoice_date) AS first_purchase_date,
               max(invoice_date) AS last_purchase_date
        FROM silver_lines WHERE customer_id IS NOT NULL GROUP BY customer_id""",
    attributes=["country", "first_purchase_date", "last_purchase_date"],
    unknown_values="NULL AS customer_id, 'Unknown' AS country, "
    "NULL AS first_purchase_date, NULL AS last_purchase_date",
)

scd1_merge(
    T_DIM_COUNTRY,
    ddl_columns="""country_key BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
          country_name STRING NOT NULL, is_unspecified BOOLEAN""",
    natural_key="country_name",
    source_sql="""SELECT DISTINCT country AS country_name, country = 'Unspecified' AS is_unspecified
                  FROM silver_lines""",
    attributes=["is_unspecified"],
    unknown_values="'Unknown' AS country_name, true AS is_unspecified",
)

