# MAGIC %md ## Gold aggregates (what the dashboard reads)

# COMMAND ----------

spark.sql(f"""
    CREATE OR REPLACE TABLE {T_AGG_MONTHLY_COUNTRY} AS
    SELECT d.year_month, g.country_name,
           sum(CASE WHEN NOT f.is_cancelled THEN f.line_amount ELSE 0 END) AS gross_sales,
           sum(CASE WHEN f.is_cancelled THEN f.line_amount ELSE 0 END)     AS cancelled_amount,
           sum(f.line_amount)                                              AS net_revenue,
           count(DISTINCT CASE WHEN NOT f.is_cancelled THEN f.invoice_no END) AS invoices,
           count(DISTINCT CASE WHEN f.customer_key <> {UNKNOWN_KEY} THEN f.customer_key END) AS customers
    FROM {T_FACT} f
    JOIN {T_DIM_DATE} d    ON d.date_key = f.date_key
    JOIN {T_DIM_COUNTRY} g ON g.country_key = f.country_key
    GROUP BY d.year_month, g.country_name
""")

spark.sql(f"""
    CREATE OR REPLACE TABLE {T_AGG_TOP_PRODUCTS} AS
    SELECT p.product_key, p.stock_code, p.description,
           sum(f.line_amount)            AS net_revenue,
           sum(f.quantity)               AS net_units,
           count(DISTINCT f.invoice_no)  AS invoices,
           rank() OVER (ORDER BY sum(f.line_amount) DESC) AS revenue_rank
    FROM {T_FACT} f
    JOIN {T_DIM_PRODUCT} p ON p.product_key = f.product_key
    WHERE NOT p.is_non_merchandise
    GROUP BY p.product_key, p.stock_code, p.description
""")

spark.sql(f"""
    CREATE OR REPLACE TABLE {T_AGG_CANCELLATION_RATE} AS
    SELECT d.year_month,
           sum(CASE WHEN NOT f.is_cancelled THEN f.line_amount ELSE 0 END)   AS gross_sales,
           -sum(CASE WHEN f.is_cancelled THEN f.line_amount ELSE 0 END)      AS cancelled_amount,
           round(-sum(CASE WHEN f.is_cancelled THEN f.line_amount ELSE 0 END)
                 / sum(CASE WHEN NOT f.is_cancelled THEN f.line_amount ELSE 0 END), 4) AS cancellation_rate
    FROM {T_FACT} f
    JOIN {T_DIM_DATE} d ON d.date_key = f.date_key
    GROUP BY d.year_month
""")

