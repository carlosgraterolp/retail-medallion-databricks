# MAGIC %md ## fact_sales (grain: one invoice line)
# MAGIC Full rebuild from silver. Dimension lookups use the natural keys; a missing match maps to -1.
# MAGIC Liquid clustering on `date_key` replaces Hive-style partitioning: at ~1M rows, partitioning
# MAGIC would only create many small files.

# COMMAND ----------

fact = spark.sql(f"""
    SELECT
      s.line_id,
      s.invoice_no,                                            -- degenerate dimension
      CAST(date_format(s.invoice_date, 'yyyyMMdd') AS INT)     AS date_key,
      coalesce(p.product_key,  {UNKNOWN_KEY})                  AS product_key,
      coalesce(c.customer_key, {UNKNOWN_KEY})                  AS customer_key,
      coalesce(g.country_key,  {UNKNOWN_KEY})                  AS country_key,
      s.invoice_ts,
      s.quantity,
      s.unit_price,
      s.line_amount,                                           -- negative for cancellations
      s.is_cancelled
    FROM silver_lines s
    LEFT JOIN {T_DIM_PRODUCT}  p ON p.stock_code   = s.stock_code
    LEFT JOIN {T_DIM_CUSTOMER} c ON c.customer_id  = s.customer_id
    LEFT JOIN {T_DIM_COUNTRY}  g ON g.country_name = s.country
""")
(
    fact.write.format("delta").mode("overwrite").option("overwriteSchema", True)
    .clusterBy("date_key")
    .saveAsTable(T_FACT)
)

spark.sql(f"COMMENT ON TABLE {T_FACT} IS 'Grain: one invoice line. Measures: quantity, unit_price, line_amount (negative = cancellation).'")
spark.sql(f"COMMENT ON TABLE {T_DIM_PRODUCT} IS 'SCD Type 1. Natural key: stock_code. product_key = -1 is the unknown member.'")
spark.sql(f"COMMENT ON TABLE {T_DIM_CUSTOMER} IS 'SCD Type 1. Natural key: customer_id. customer_key = -1 is guest/unknown.'")

